/** Extra words a section is known by. Pure. */
export const sectionAliases = (name: string): string[] => (SECTION_ALIASES[name] ?? '').split(' ').filter(Boolean);

const BY_FORM = new Map(Object.entries(VOCAB).map(([k, v]) => [skeleton(k), v]));

/** The classical words a question's word stands for ([] when it has no other name). Pure. */
export function classicalWords(word: string): string[] {
  const norm = normWord(word);
  for (const w of [norm, ...unprefixed(norm)]) {
    const hit = BY_FORM.get(skeleton(w));
    if (hit) return hit;
  }
  return [];
}
